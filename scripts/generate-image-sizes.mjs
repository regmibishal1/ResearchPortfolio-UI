// Writes src/app/data/image-sizes.ts: the pixel size of every content image
// (blog figures, project screenshots, diagrams, research figures). The image
// components read it to set width and height, so the browser reserves the
// space before a lazy image loads and the text below it never jumps. Runs
// before every build, like the sitemap; sizes come from the file headers.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { root } from './lib/load-data.mjs'

const DIRS = [
  'src/assets/blog',
  'src/assets/projects',
  'src/assets/research',
  'src/assets/diagrams',
]

function webpSize(b) {
  const chunk = b.toString('ascii', 12, 16)
  if (chunk === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff]
  if (chunk === 'VP8L') {
    const bits = b.readUInt32LE(21)
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1]
  }
  if (chunk === 'VP8X') return [b.readUIntLE(24, 3) + 1, b.readUIntLE(27, 3) + 1]
  return null
}

function jpegSize(b) {
  let i = 2
  while (i < b.length) {
    if (b[i] !== 0xff) return null
    const marker = b[i + 1]
    const length = b.readUInt16BE(i + 2)
    // SOF0-SOF15, except DHT (C4), JPG (C8) and DAC (CC), carry the frame size.
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)]
    }
    i += 2 + length
  }
  return null
}

function svgSize(text) {
  const tag = text.match(/<svg[^>]*>/)?.[0] ?? ''
  const num = (name) => Number(tag.match(new RegExp(`\\b${name}="([\\d.]+)(px)?"`))?.[1])
  const [w, h] = [num('width'), num('height')]
  if (w && h) return [Math.round(w), Math.round(h)]
  const box = tag.match(/viewBox="[\d.-]+[ ,]+[\d.-]+[ ,]+([\d.]+)[ ,]+([\d.]+)"/)
  return box ? [Math.round(Number(box[1])), Math.round(Number(box[2]))] : null
}

function sizeOf(file) {
  const b = readFileSync(file)
  if (file.endsWith('.png')) return [b.readUInt32BE(16), b.readUInt32BE(20)]
  if (file.endsWith('.webp')) return webpSize(b)
  if (/\.jpe?g$/.test(file)) return jpegSize(b)
  if (file.endsWith('.svg')) return svgSize(b.toString('utf8'))
  return null
}

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })

const sizes = {}
for (const dir of DIRS) {
  for (const file of walk(resolve(root, dir))) {
    if (!/\.(png|webp|jpe?g|svg)$/.test(file)) continue
    const size = sizeOf(file)
    if (!size) throw new Error(`generate-image-sizes: cannot read the size of ${file}`)
    const key = relative(resolve(root, 'src'), file).split('\\').join('/')
    sizes[key] = size
  }
}

const entries = Object.keys(sizes)
  .sort()
  .map((key) => `  '${key}': [${sizes[key][0]}, ${sizes[key][1]}],`)
const out =
  '// Generated by scripts/generate-image-sizes.mjs before each build. Do not edit.\n' +
  '/** Pixel width and height of each content image, by its path under src/. */\n' +
  'export const IMAGE_SIZES: Record<string, [number, number]> = {\n' +
  entries.join('\n') +
  '\n}\n'
writeFileSync(resolve(root, 'src/app/data/image-sizes.ts'), out)
console.log(`image-sizes.ts: ${entries.length} images`)
